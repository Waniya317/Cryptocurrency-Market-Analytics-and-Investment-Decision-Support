import requests
import json
import os
from dotenv import load_dotenv

load_dotenv()

API_KEY = os.getenv("COINGECKO_API_KEY")
#API_KEY = 'CG-Pi8iNoVbVck4iGJiNu9sZFzE'
url = "https://api.coingecko.com/api/v3/coins/bitcoin/market_chart"

params = {
    "vs_currency": "usd",
    "days": "365",
    "interval": "daily"

}

headers = {
    "x-cg-demo-api-key": API_KEY
}

response = requests.get(url, params=params, headers=headers)

data = response.json()

os.makedirs("data/raw/full_load", exist_ok=True)

with open("data/raw/full_load/bitcoin_365_days.json", "w") as file:
    json.dump(data, file, indent=4)

